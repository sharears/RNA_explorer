const assert=require("node:assert/strict"),fs=require("node:fs");
const doc={readyState:"loading",addEventListener(){}};
const motifSource=fs.readFileSync(__dirname+"/../secondary-motifs.js","utf8");
const lessonSource=fs.readFileSync(__dirname+"/../guided-secondary-learning.js","utf8");
const base=new Function("document",motifSource+"\nreturn SecondaryMotifExplorer;")(doc);
const lesson=new Function("document",lessonSource+"\nreturn GuidedSecondaryLearning;")(doc);
const find=dot=>lesson.buildMotifs("A".repeat(dot.length),dot,base.identify);
const tRNA="(((((((..((((........)))).(((((.......))))).....(((((.......))))))))))))....";
const types=["stem","hairpin","hairpinLoop","internal","bulge","junction"];
const found=find(tRNA),counts=Object.fromEntries(types.map(type=>[type,found.filter(m=>m.type===type).length]));
assert.deepEqual(counts,{stem:4,hairpin:3,hairpinLoop:3,internal:0,bulge:0,junction:1});
assert.deepEqual(found.filter(m=>m.type==="stem").map(m=>m.size).sort((a,b)=>a-b),[4,5,5,7]);
const hp=found.filter(m=>m.type==="hairpin"),loops=found.filter(m=>m.type==="hairpinLoop");
assert.deepEqual(hp.map(m=>m.indices.length).sort((a,b)=>a-b),[9,9,10]);
assert.deepEqual(hp.map(m=>m.pairs.length),[1,1,1]);
assert.deepEqual(loops.map(m=>m.pairs.length),[0,0,0]);
assert.deepEqual(found.find(m=>m.type==="junction").pairs.length,4);
const internal=find("(.(..).)").find(m=>m.type==="internal");
assert.deepEqual(internal.pairs,[[0,7],[2,5]]);
assert.deepEqual(internal.indices,[0,1,2,5,6,7]);
const bulge=find("(.(..))").find(m=>m.type==="bulge");
assert.deepEqual(bulge.pairs,[[0,6],[2,5]]);
assert.deepEqual(bulge.indices,[0,1,2,5,6]);
const stem=find("(((...)))").find(m=>m.type==="stem");
assert.equal(stem.size,3);
assert.equal(find("((...))").some(m=>m.type==="stem"),false);
console.log("PASS: 6 motifs, all tRNA occurrences, three-pair minimum, exact loop and closing-pair boundaries");
