import {chromium} from "playwright";
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on("pageerror",e=>errors.push(String(e)));
try {
 await page.goto(process.env.RNA_EXPLORER_URL||"http://127.0.0.1:4173/?page=secondary&start=example",{waitUntil:"domcontentloaded"});
 await page.waitForFunction(()=>typeof SecondaryMotifExplorer!=="undefined"&&SecondaryMotifExplorer.getMotifs().length>0);
 await page.locator('#scene-secondary [data-rna-tab="analyze"]').click();
 if(!(await page.locator("#seMotifTools").isVisible()))throw Error("Motif tools are not visible in Inspect.");
 const motifCount=await page.evaluate(()=>SecondaryMotifExplorer.getMotifs().filter(m=>m.type==="hairpin").length);
 if(motifCount!==3)throw Error("Default tRNA should contain three hairpin loops: "+motifCount);
 if(!(await page.locator("#seMotifShow-bulge").isDisabled()))throw Error("Missing bulges should have a disabled gray option.");
 await page.locator("#seMotifShow-hairpin").click();
 const loopNucleotides=await page.evaluate(()=>SecondaryMotifExplorer.getMotifs().filter(m=>m.type==="hairpin").reduce((n,m)=>n+m.size,0));
 if((await page.locator("#secondarySvg .se-motif-ring").count())!==loopNucleotides)throw Error("All hairpin loop residues were not outlined.");
 await page.locator('[data-secondary-layout="circular"]').click();
 if((await page.locator("#secondarySvg .se-motif-ring").count())!==loopNucleotides)throw Error("Highlights did not survive a layout change.");
 const sizeOptions=await page.locator("#seMotifSize").evaluate(el=>[...el.options].map(o=>({value:o.value,disabled:o.disabled}))); 
 if(!sizeOptions.find(o=>o.value==="3")?.disabled||!sizeOptions.find(o=>o.value==="4")?.disabled)throw Error("Unavailable 3- and 4-nucleotide hairpins should be disabled: "+JSON.stringify(sizeOptions));
 await page.selectOption("#seMotifSize","7");
 await page.locator("#seMotifStart").click();
 if((await page.locator("#secondarySvg .se-motif-ring").count())!==0)throw Error("Challenge gave away the answer before submission.");
 const target=await page.evaluate(()=>SecondaryMotifExplorer.getMotifs().find(m=>m.type==="hairpin"&&m.size===7).indices);
 for(const i of target)await page.locator('#secondarySvg [data-residue-index="'+i+'"]').click();
 const count=await page.evaluate(()=>SecondaryExplorer.getContext().selectedResidues.length);
 if(count!==target.length)throw Error("Single clicks did not accumulate the challenge selection: "+count);
 await page.locator("#seMotifCheck").click();
 if(!/Correct!/.test(await page.locator("#seMotifStatus").textContent()))throw Error("Correct answer was not accepted.");
 if((await page.locator("#secondarySvg .se-motif-ring").count())!==target.length)throw Error("Answer feedback did not outline correct loop.");
 await page.locator("#seMotifStop").click();
 await page.fill("#secondarySequence","AAAAAAAA");
 await page.fill("#secondaryDotBracket","(.(..).)");
 await page.click("#renderSecondaryButton");
 await page.waitForFunction(()=>SecondaryMotifExplorer.getMotifs().some(m=>m.type==="internal"));
 if(await page.locator("#seMotifShow-internal").isDisabled())throw Error("Internal loops remained disabled after structure changed.");
 await page.locator("#seMotifShow-internal").click();
 if((await page.locator("#secondarySvg .se-motif-ring").count())!==2)throw Error("Internal-loop highlighting should mark only two unpaired nucleotides.");
 const serious=errors.filter(s=>!/favicon|ResizeObserver loop/i.test(s));
 if(serious.length)throw Error("Browser errors: "+serious.join("; "));
 console.log("PASS: Secondary motif explorer + challenge browser smoke test");
} finally {await browser.close();}
